"""Prompts for draft-model training data: conversations whose last turn the target will answer.

    $PY tools/draft/prompts.py OUT_DIR [--source perfectblend|local] [--train N] [--eval M] [--seed S]

Writes OUT_DIR/train.prompts.jsonl and OUT_DIR/eval.prompts.jsonl, one conversation per line:
{"id": ..., "source": ..., "messages": [{"role": "user" | "assistant" | "system", "content": ...}]},
ending on a user turn. Earlier assistant turns stay as the dataset wrote them (the target sees them
as context); only the last answer is regenerated by the target (regenerate.py), so the drafter
learns the target's own outputs, as EAGLE-3, DFlash and DSpark all do.

Sources:
  perfectblend  mlabonne/open-perfectblend, DSpark's training prompts (about 1.3M conversations:
                chat 17.6%, math 39.4%, code 38.9%, instruction following 4.1%). Downloads it.
  local         a small offline mix from datasets already cached on the server (math problems,
                coding tasks, reading comprehension, essays to summarize), for smoke tests.
"""

import argparse
import json
import pathlib
import random

MAX_CHARS = 12000  # a prompt longer than this is cut out (the features pass caps sequences anyway)


def from_perfectblend():
    from datasets import load_dataset

    ds = load_dataset("mlabonne/open-perfectblend", split="train")
    roles = {"human": "user", "user": "user", "gpt": "assistant", "assistant": "assistant", "system": "system"}
    for i, row in enumerate(ds):
        turns = row.get("conversations") or row.get("messages") or []
        msgs = []
        for t in turns:
            role = roles.get(t.get("from") or t.get("role"))
            text = t.get("value") if "value" in t else t.get("content")
            if role and text:
                msgs.append({"role": role, "content": text})
        while msgs and msgs[-1]["role"] != "user":
            msgs.pop()  # answer the last user turn
        if msgs:
            yield {"id": f"pb-{i}", "source": row.get("source", "perfectblend"), "messages": msgs}


def from_local():
    """Offline: whichever of these the server's datasets cache holds."""
    import os

    os.environ.setdefault("HF_DATASETS_OFFLINE", "1")
    from datasets import load_dataset

    def user(text):
        return [{"role": "user", "content": text}]

    builders = [
        ("omni-math", lambda: load_dataset("KbsdJames/Omni-MATH", split="test"), lambda r: user(r["problem"])),
        ("mbpp", lambda: load_dataset("google-research-datasets/mbpp", split="test"),
         lambda r: user(f"Write a Python function for this task, with a short explanation.\n\n{r['text']}")),
        ("drop", lambda: load_dataset("EleutherAI/drop", split="validation"),
         lambda r: user(f"{r['passage']}\n\nQuestion: {r['question']}\nAnswer, and explain how you found it.")),
        ("essays", lambda: load_dataset("baber/paul_graham_essays", split="train"),
         lambda r: user(f"Summarize this essay in a few paragraphs.\n\n{r['text'][:8000]}")),
    ]
    for name, load, to_msgs in builders:
        try:
            ds = load()
        except Exception as e:  # not cached here: skip it
            print(f"local source {name}: unavailable ({type(e).__name__})")
            continue
        for i, row in enumerate(ds):
            yield {"id": f"{name}-{i}", "source": name, "messages": to_msgs(row)}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out_dir")
    ap.add_argument("--source", default="perfectblend", choices=["perfectblend", "local"])
    ap.add_argument("--train", type=int, default=200000)
    ap.add_argument("--eval", type=int, default=96)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    rows = list(from_perfectblend() if args.source == "perfectblend" else from_local())
    rows = [r for r in rows if sum(len(m["content"]) for m in r["messages"]) <= MAX_CHARS]
    seen, unique = set(), []
    for r in rows:  # exact duplicates of the last user turn add nothing
        key = r["messages"][-1]["content"].strip()
        if key not in seen:
            seen.add(key)
            unique.append(r)
    random.Random(args.seed).shuffle(unique)
    if args.source == "local":  # interleave the small sources so any prefix is a mix
        by = {}
        for r in unique:
            by.setdefault(r["source"], []).append(r)
        unique = [r for group in zip(*by.values()) for r in group]
    ev, tr = unique[: args.eval], unique[args.eval : args.eval + args.train]
    out = pathlib.Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for name, part in (("eval", ev), ("train", tr)):
        with open(out / f"{name}.prompts.jsonl", "w") as f:
            for r in part:
                f.write(json.dumps(r) + "\n")
    sources = {}
    for r in tr:
        sources[r["source"]] = sources.get(r["source"], 0) + 1
    print(f"{len(tr)} train and {len(ev)} eval conversations in {out}; train sources: "
          + ", ".join(f"{k} {v}" for k, v in sorted(sources.items(), key=lambda kv: -kv[1])[:12]))


if __name__ == "__main__":
    main()
