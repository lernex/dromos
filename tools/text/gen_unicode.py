#!/usr/bin/env python3
"""Generates engine/text/unicode_tables.inc from Python's unicodedata.

    python3 tools/text/gen_unicode.py > engine/text/unicode_tables.inc

Run on the GPU server (its Python has Unicode 16.0.0, the version the tokenizers crate classes
were checked against; see the probe in the commit that added this file). The tables are the
classes the Metis pre-tokenizer regex and the Python-semantics helpers depend on:

  kLetter       \\p{L}: Lu Ll Lt Lm Lo
  kNumber       \\p{N}: Nd Nl No
  kRegexSpace   \\s as the regex engines use it: the White_Space property
  kPySpace      str.isspace(), what str.strip() removes (it adds U+001C..U+001F)
  kDecimal      Nd digits with their values, as int() and float() read them
"""

import sys
import unicodedata

import regex

# White_Space (UAX #44), the set \s matches in the tokenizers regex and in the `regex` module.
WHITE_SPACE = (
    list(range(0x09, 0x0E))
    + [0x20, 0x85, 0xA0, 0x1680]
    + list(range(0x2000, 0x200B))
    + [0x2028, 0x2029, 0x202F, 0x205F, 0x3000]
)


def ranges(members):
    out = []
    start = prev = None
    for cp in members:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            out.append((start, prev))
            start = prev = cp
    if start is not None:
        out.append((start, prev))
    return out


def main():
    cats = [unicodedata.category(chr(cp)) for cp in range(0x110000)]
    letters = [cp for cp, c in enumerate(cats) if c in ("Lu", "Ll", "Lt", "Lm", "Lo")]
    numbers = [cp for cp, c in enumerate(cats) if c in ("Nd", "Nl", "No")]
    regex_space = [cp for cp in range(0x110000) if regex.match(r"\s", chr(cp))]
    assert regex_space == sorted(WHITE_SPACE), "regex \\s is not the White_Space set"
    py_space = [cp for cp in range(0x110000) if chr(cp).isspace()]
    decimal = []
    for cp, c in enumerate(cats):
        if c == "Nd":
            decimal.append((cp, unicodedata.decimal(chr(cp))))
    # Runs where the digit value rises by one with the code point.
    digit_runs = []
    for cp, value in decimal:
        if digit_runs and digit_runs[-1][1] == cp - 1 and digit_runs[-1][2] + (cp - digit_runs[-1][0]) == value:
            digit_runs[-1][1] = cp
        else:
            digit_runs.append([cp, cp, value])

    out = sys.stdout
    out.write("// Generated by tools/text/gen_unicode.py from Python unicodedata %s. Do not edit.\n"
              % unicodedata.unidata_version)

    def emit(name, rs):
        out.write("constexpr Range %s[] = {\n" % name)
        for lo, hi in rs:
            out.write("    {0x%04X, 0x%04X},\n" % (lo, hi))
        out.write("};\n\n")

    emit("kLetter", ranges(letters))
    emit("kNumber", ranges(numbers))
    emit("kRegexSpace", ranges(regex_space))
    emit("kPySpace", ranges(py_space))
    out.write("constexpr DigitRun kDecimal[] = {\n")
    for lo, hi, value in digit_runs:
        out.write("    {0x%04X, 0x%04X, %d},\n" % (lo, hi, value))
    out.write("};\n")


if __name__ == "__main__":
    main()
