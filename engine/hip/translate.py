#!/usr/bin/env python3
"""Regenerate the HIP backend's sources from the CUDA kernels.

    translate.py generate        engine/cuda -> engine/hip/src (rules, then patches), and check the result
    translate.py save FILE...    write engine/hip/patches/FILE.patch from the hand-edited src/FILE
    translate.py check           fail if src/ is not what generate would produce

Three layers. The rules are mechanical: CUDA names become their HIP names (cudaMalloc -> hipMalloc,
cublasLt -> hipblasLt, __nv_bfloat16 -> __hip_bfloat16), the warp shuffles take the 32-lane width
(lx_shfl_*), and the NVIDIA-only constructs the port does not use (thread-block clusters, cp.async,
programmatic dependent launch, the inline PTX of the FP8 and FP4 conversions) become the portable forms
in include/. The handwritten files are copied from include/ in place of their CUDA source: mma.cuh (the
tensor-core helpers, lx_mma.cuh) and the FP8/FP4, block-scan and runtime headers they include. The
patches are the structural changes a rename cannot make: the attention tile size on the workgroup's LDS
and the split-K launch that HIP does not offer.

Warp model: a warp is 32 lanes (threadIdx.x & 31, threadIdx.x >> 5), as in the CUDA sources. A wave64
holds two such warps, and every shuffle is width 32, so each warp reduces within its own lanes. Nothing
here depends on the wavefront size.

A patch applies to the output of the rules for its file. When the CUDA source changes and a patch no
longer applies, `generate` stops and names the file: re-port that file's change by hand in src/, then
`save` it again. kernels.h and tunable.h are the ABI and are copied verbatim.
"""

import difflib
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CUDA = os.path.join(ROOT, "engine", "cuda")
SRC = os.path.join(HERE, "src")
PATCHES = os.path.join(HERE, "patches")

BANNER = (
    "// Generated by engine/hip/translate.py from engine/cuda/{name}, then patched. Edit src/{name} and\n"
    "// run `translate.py save {name}` to keep the change; do not edit the rules output by hand.\n"
)

# Files copied verbatim: the ABI and the tuning interface.
VERBATIM = {"kernels.h", "tunable.h"}

# Files whose HIP form is written by hand under include/: the CUDA file's place in src/ is taken by the
# include/ file, unchanged. mma.cuh is the PTX tensor-core header; lx_mma.cuh has the same interface.
HANDWRITTEN = {"mma.cuh": "lx_mma.cuh"}

# Identifier renames, applied in order. The generic cuda -> hip and cublas -> hipblas rules come last,
# so the specific ones above them win.
RENAMES = [
    (r"__nv_bfloat162", "__hip_bfloat162"),
    (r"__nv_bfloat16", "__hip_bfloat16"),
    (r"__float2bfloat16_rn", "__float2bfloat16"),
    (r"\bcudaErrorMemoryAllocation\b", "hipErrorOutOfMemory"),
    (r"\bcudaTriggerProgrammaticLaunchCompletion\b", "lx_pdl_trigger"),
    (r"\bcudaGridDependencySynchronize\b", "lx_pdl_wait"),
    (r"\bcudaLaunchKernelEx\b", "lx_launch_kernel_ex"),
    (r"\bcudaLaunchConfig_t\b", "lx_launch_config"),
    (r"\bcudaLaunchAttributeProgrammaticStreamSerialization\b", "LX_LAUNCH_ATTR_PDL"),
    (r"\bcudaLaunchAttributeCooperative\b", "LX_LAUNCH_ATTR_COOPERATIVE"),
    (r"\bcudaLaunchAttribute\b", "lx_launch_attr"),
    (r"\b__ldg\(", "lx_ldg("),
    (r"\b__ldcs\(", "lx_ldcs("),
    (r"\b__pipeline_memcpy_async\(", "lx_pipeline_memcpy_async("),
    (r"\b__pipeline_commit\(", "lx_pipeline_commit("),
    (r"\b__pipeline_wait_prior\(", "lx_pipeline_wait_prior("),
    (r"\bLX_BACKEND_CUDA\b", "LX_BACKEND_HIP"),
    (r"\bcudaErrorInvalidValue\b", "hipErrorInvalidValue"),
    (r"\bCUBLASLT_", "HIPBLASLT_"),
    (r"\bcublasLt", "hipblasLt"),
    (r"\bCUBLAS_", "HIPBLAS_"),
    (r"\bcublas", "hipblas"),
    (r"\bCUDA_R_", "HIP_R_"),
    (r"\bcudaDataType\b", "hipDataType"),
    # HIP has no thread-block clusters: no architecture takes the cluster path (common.cuh).
    (r"\blx::kClusterArch\b", "lx::kNoClusterArch"),
    (r"\bcudaFuncSetAttribute\(", "lx_func_set_attribute("),
    (r"\b__shfl_sync\(", "lx_shfl_sync("),
    (r"\b__shfl_xor_sync\(", "lx_shfl_xor_sync("),
    (r"\b__shfl_down_sync\(", "lx_shfl_down_sync("),
    (r"\b__shfl_up_sync\(", "lx_shfl_up_sync("),
    (r"\b__match_any_sync\(", "lx_match_any_sync("),
    (r"\b__reduce_max_sync\(", "lx_reduce_max_sync("),
    (r"\b__reduce_add_sync\(", "lx_reduce_add_sync("),
    (r"\bcudaDevAttrMultiProcessorCount\b", "hipDeviceAttributeMultiprocessorCount"),
    (r"\bcudaDeviceProp\b", "hipDeviceProp_t"),
    (r"\bcudaPointerAttributes\b", "hipPointerAttribute_t"),
    (r"\bcudaDeviceAttr\b", "hipDeviceAttribute_t"),
    (r"\bcudaDevAttrGlobalMemoryBusWidth\b", "hipDeviceAttributeMemoryBusWidth"),
    (r"\bcudaDevAttr([A-Z])", r"hipDeviceAttribute\1"),
    (r"\bcuda([A-Z_])", r"hip\1"),
]

INCLUDES = [
    (r"#include <cuda_runtime\.h>", '#include "lx_hip.h"'),
    (r"#include <cuda_bf16\.h>\n", ""),
    (r"#include <cuda_pipeline\.h>\n", ""),
    (r"#include <cooperative_groups\.h>\n", ""),
    (r"namespace cg = cooperative_groups;\n", ""),
    (r"#include <cublasLt\.h>", "#include <hipblaslt/hipblaslt.h>"),
    (r"#include <cuda_fp16\.h>", "#include <hip/hip_fp16.h>"),
    (r"#include <cuda_fp8\.h>", '#include "lx_fp8.h"'),
    (r"#include <cuda_fp4\.h>", '#include "lx_fp8.h"'),
    (r"#include <cub/block/block_scan\.cuh>", '#include "lx_cub.h"'),
    (r"#include <cub/cub\.cuh>", '#include "lx_cub.h"'),
    (r'#include "cuda/', '#include "'),
]

# Cluster attributes have no HIP form; kernels that used them are removed by the patches, and any
# left over are dropped here so the rules output still compiles on its own.
DROPS = [
    (r"__cluster_dims__\([^)]*\)[ \t]*", ""),
]


def rules(text):
    for pat, rep in INCLUDES:
        text = re.sub(pat, rep, text)
    for pat, rep in DROPS:
        text = re.sub(pat, rep, text)
    for pat, rep in RENAMES:
        text = re.sub(pat, rep, text)
    return text


def base_text(name):
    """The rules output for one CUDA file, with the banner."""
    if name in HANDWRITTEN:
        with open(os.path.join(HERE, "include", HANDWRITTEN[name]), encoding="utf-8") as f:
            return f.read()
    with open(os.path.join(CUDA, name), encoding="utf-8") as f:
        text = f.read()
    if name in VERBATIM:
        return text
    return BANNER.format(name=name) + rules(text)


def sources():
    names = sorted(n for n in os.listdir(CUDA) if n.endswith((".cu", ".cuh", ".h")))
    return names


def patch_path(name):
    return os.path.join(PATCHES, name + ".patch")


def generate_one(name, workdir):
    base = os.path.join(workdir, name)
    with open(base, "w", encoding="utf-8") as f:
        f.write(base_text(name))
    out = os.path.join(SRC, name)
    p = patch_path(name)
    if os.path.exists(p):
        r = subprocess.run(
            ["patch", "--no-backup-if-mismatch", "-s", "-o", out, base, p],
            capture_output=True,
            text=True,
        )
        if r.returncode != 0:
            sys.exit(f"translate: patch for {name} does not apply; re-port it by hand\n{r.stdout}{r.stderr}")
    else:
        with open(out, "w", encoding="utf-8") as f:
            f.write(base_text(name))


def generate():
    os.makedirs(SRC, exist_ok=True)
    os.makedirs(PATCHES, exist_ok=True)
    with tempfile.TemporaryDirectory() as work:
        for name in sources():
            generate_one(name, work)
    # Drop generated files whose CUDA source is gone.
    for name in os.listdir(SRC):
        if name not in sources():
            os.remove(os.path.join(SRC, name))
    print(f"translate: wrote {len(sources())} files to {SRC}")


def save(names):
    os.makedirs(PATCHES, exist_ok=True)
    with tempfile.TemporaryDirectory() as work:
        for name in names:
            base = base_text(name)
            with open(os.path.join(SRC, name), encoding="utf-8") as f:
                edited = f.read()
            if base == edited:
                if os.path.exists(patch_path(name)):
                    os.remove(patch_path(name))
                print(f"translate: {name} matches the rules, no patch")
                continue
            diff = difflib.unified_diff(
                base.splitlines(keepends=True),
                edited.splitlines(keepends=True),
                fromfile=f"a/{name}",
                tofile=f"b/{name}",
            )
            with open(patch_path(name), "w", encoding="utf-8") as f:
                f.writelines(diff)
            print(f"translate: saved {patch_path(name)}")


def check():
    with tempfile.TemporaryDirectory() as work:
        bad = []
        for name in sources():
            # Regenerate into a scratch directory and compare with what is committed.
            base = os.path.join(work, name)
            with open(base, "w", encoding="utf-8") as f:
                f.write(base_text(name))
            want = os.path.join(work, "out-" + name)
            p = patch_path(name)
            if os.path.exists(p):
                r = subprocess.run(
                    ["patch", "--no-backup-if-mismatch", "-s", "-o", want, base, p],
                    capture_output=True,
                    text=True,
                )
                if r.returncode != 0:
                    bad.append(name + " (patch does not apply)")
                    continue
                with open(want, encoding="utf-8") as f:
                    want_text = f.read()
            else:
                want_text = base_text(name)
            with open(os.path.join(SRC, name), encoding="utf-8") as f:
                if f.read() != want_text:
                    bad.append(name)
        if bad:
            sys.exit("translate: src/ is stale for: " + ", ".join(bad) + "\nrun `translate.py generate`")
        print("translate: src/ matches the CUDA sources and the patches")


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    cmd = argv[1]
    if cmd == "generate":
        generate()
        check()
    elif cmd == "save":
        save(argv[2:])
    elif cmd == "check":
        check()
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
